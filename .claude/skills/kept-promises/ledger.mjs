#!/usr/bin/env node
/**
 * kept-promises — every instruction the owner gave, and whether anything actually landed for it.
 *
 * The owner, 2026-08-28: "how are you gna prove to me that you acc implement the things I say
 * because for example if I don't ask you will just move on as if it's been implemented and I don't
 * know how many things you have done that for."
 *
 * That is unanswerable by promising harder. It needs a COUNT, produced by reading the record rather
 * than by remembering it — which is the same shape as correction-capture and for the same reason:
 * the failure mode is forgetting, so the mechanism cannot depend on remembering.
 *
 * What it does: pull every instruction-shaped owner turn out of the transcript, then go looking in
 * git history for evidence that something landed for it AFTER it was given. Three verdicts, and the
 * middle one is the entire point:
 *
 *   KEPT      — a commit after that turn matches the instruction strongly.
 *   WEAK      — something matches, but thinly. Worth a human's eyes.
 *   NO TRACE  — nothing in the history matches. Either it was dropped, or it was answered in chat
 *               and never needed a commit. THE TOOL CANNOT TELL THOSE APART and does not pretend to.
 *
 * NO TRACE is a REVIEW LIST, not an accusation. Keyword matching over commit messages is coarse:
 * it will miss work whose commit used different words, and it will credit a commit that merely
 * mentioned the right noun. Stated here because a number presented as more precise than it is would
 * be worse than no number at all.
 *
 *   node ledger.mjs                 # audit the newest transcript
 *   node ledger.mjs --all           # every transcript on this container
 *   node ledger.mjs --open          # only what has NO TRACE — the review list
 *   node ledger.mjs --selftest
 */

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

/* ------------------------------------------------------------------ owner speech */

export const MACHINE_PREFIXES = [
  "This session is being continued from a previous conversation",
  "Base directory for this skill:",
  "Caveat: The messages below were generated by the user while running local commands",
  "<command-name>",
  "Prompt is too long",
];

export function isMachineTurn(text) {
  const t = (text || "").trimStart();
  return MACHINE_PREFIXES.some((p) => t.startsWith(p));
}

export function stripInjected(s) {
  return String(s)
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "")
    .replace(/<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g, "")
    .trim();
}

export function userText(msg) {
  const c = msg?.content;
  if (typeof c === "string") return stripInjected(c);
  if (!Array.isArray(c)) return "";
  const parts = [];
  for (const b of c) {
    if (!b || typeof b !== "object") continue;
    if (b.type === "tool_result") return "";
    if (b.type === "text" && typeof b.text === "string") parts.push(b.text);
  }
  return stripInjected(parts.join("\n"));
}

/* ------------------------------------------------------------------ is it an instruction? */

// An instruction asks for a CHANGE. A question, a link with no verb, and an acknowledgement all
// look superficially similar in a transcript and none of them create an obligation.
const IMPERATIVE =
  /\b(build|implement|make|add|create|write|fix|change|update|remove|delete|set\s?up|wire|install|use|run|check|verify|prove|test|record|track|store|keep|stop|start|enable|disable|rename|move|refactor|ship|deploy|publish|push|commit|scan|audit|ratchet|budget)\b/i;
const REQUEST_FRAME =
  /\b(i want|i need|can u|can you|could u|could you|pls|please|make sure|ensure|from now on|next time|going forward|always|never|gotta|you should|u should|do it|go ahead)\b/i;

// Things that look like instructions and are not.
const NOT_AN_INSTRUCTION = [
  /^\s*(next|next reel|explain \d+|next reel.*)\s*$/i,   // navigation through a list
  /^\s*(ok|okay|k|yes|no|ty|thanks|cool|nice|sure|got it)\b/i,
  /^\s*https?:\/\/\S+\s*$/i,                              // a bare link
  // An interrogative opening asks ABOUT the work; it does not commission any. "how did u implement
  // reel 8" contains the verb "implement" and creates no obligation whatsoever.
  /^\s*(how|what|why|when|where|which|who)\s+(did|do|does|is|are|was|were|have|has|had|can|could|would|will|am|u|you)\b/i,
  // A pasted exercise is not a standing instruction. The owner sends coding-assessment prompts to be
  // solved in chat; they are written in third person about a hypothetical, and nothing is owed to
  // them afterwards. Without this they became permanent NO-TRACE entries nobody could ever close.
  /\b(your task is to|you are given|task business|in this task|consisting of decimal digits)\b/i,
];

export function isInstruction(text) {
  const t = (text || "").trim();
  if (!t || t.length < 8) return false;
  if (isMachineTurn(t)) return false;
  if (NOT_AN_INSTRUCTION.some((re) => re.test(t))) return false;
  // A question that asks for information is not an instruction — unless it also demands a change.
  const questionOnly = /\?\s*$/.test(t) && !IMPERATIVE.test(t) && !REQUEST_FRAME.test(t);
  if (questionOnly) return false;
  return IMPERATIVE.test(t) || REQUEST_FRAME.test(t);
}

/* ------------------------------------------------------------------ evidence in git */

const STOP = new Set(
  ("the a an and or but if then than that this these those is are was were be been being of in on at to for with from by as it its not no you your i we they them their what which who when where how why do does did done can could should would will just so very into over under again more most other some such only own same too now u ur im dont doesnt isnt gonna gna acc alr lmk js like want need make made get got go going one two all any also still even much many lot"
  ).split(" "),
);

export const tokenise = (s) =>
  String(s).toLowerCase().split(/[^a-z0-9+#._-]+/)
    .map((w) => w.replace(/^[._-]+|[._-]+$/g, ""))
    .filter((w) => w.length > 3 && !STOP.has(w));

export function scoreMatch(terms, haystack) {
  if (!terms.length) return 0;
  const h = haystack.toLowerCase();
  let hit = 0;
  for (const t of terms) if (h.includes(t)) hit++;
  return hit / terms.length;
}

/** Commits, newest first, as {sha, iso, subject, body, files}. */
export function loadCommits(repo = ".", limit = 400) {
  // TRAP, and it cost a completely wrong headline number before it was caught: with `--name-only`,
  // a record separator placed at the END of --pretty=format lands BEFORE the file list, so every
  // chunk after the first begins with filenames instead of a header and parses to nothing. The
  // first draft reported "1 commits searched" and therefore "25 NO TRACE" — a false accusation
  // against itself. The separator goes at the START, and the body and file list are simply kept
  // together, since both are only ever searched as text.
  let out = "";
  try {
    // execFile with an argument array, never a shell string — gate-protections/shell.mjs is the
    // reference and this file has no business being the exception. Caught by the warning ratchet
    // blocking this very commit, one turn after that ratchet shipped.
    out = execFileSync("git", [
      "-C", repo, "log", `-${Number(limit) | 0}`, "--date=iso-strict",
      "--pretty=format:%x1e%H%x1f%ad%x1f%s%x1f%b", "--name-only",
    ], { encoding: "utf8", maxBuffer: 1 << 28 });
  } catch { return []; }
  return out.split("\x1e").map((chunk) => {
    if (!chunk.trim()) return null;
    const [sha, iso, subject, rest = ""] = chunk.split("\x1f");
    if (!sha || !sha.trim()) return null;
    return { sha: sha.trim(), iso: (iso || "").trim(), subject: subject || "", body: rest, files: rest };
  }).filter(Boolean);
}

export const KEPT = 0.5, WEAK = 0.25;

export function verdictFor(instruction, commits, { after } = {}) {
  const terms = [...new Set(tokenise(instruction))];
  if (terms.length < 2) return { verdict: "unscorable", score: 0, why: "too few distinctive words to search on" };
  let best = { score: 0, commit: null };
  for (const c of commits) {
    if (after && c.iso && c.iso < after) continue;   // work BEFORE the instruction is not evidence for it
    const s = scoreMatch(terms, `${c.subject}\n${c.body}\n${c.files}`);
    if (s > best.score) best = { score: s, commit: c };
  }
  const verdict = best.score >= KEPT ? "kept" : best.score >= WEAK ? "weak" : "no-trace";
  return { verdict, score: best.score, commit: best.commit, terms };
}

/* ------------------------------------------------------------------ transcript */

/**
 * The strongest evidence available is not keyword overlap — it is a commit sha quoted back in the
 * reply. "Pushed 3b6cc42" is a claim that can be checked against git directly, so an instruction
 * followed by a reply naming a REAL commit is linked to that commit rather than guessed at.
 * A sha that does not resolve is worth more than a miss: it means a commit was claimed and none
 * exists, which is the precise failure the owner is asking about.
 */
const SHA_RE = /\b([0-9a-f]{7,40})\b/g;

function assistantText(msg) {
  const c = msg?.content;
  if (typeof c === "string") return c;
  if (!Array.isArray(c)) return "";
  return c.filter((b) => b?.type === "text" && typeof b.text === "string").map((b) => b.text).join("\n");
}

export function scanTranscript(file, { lookahead = 6 } = {}) {
  const found = [];
  const turns = [];
  let ts = "";
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line.trim()) continue;
    let d; try { d = JSON.parse(line); } catch { continue; }
    if (d.timestamp) ts = d.timestamp;
    const m = d.message;
    if (!m) continue;
    if (m.role === "user") {
      const text = userText(m);
      turns.push({ role: "user", ts, text, instruction: isInstruction(text) });
    } else if (m.role === "assistant") {
      const t = assistantText(m);
      if (t) turns.push({ role: "assistant", ts, text: t });
    }
  }
  for (let i = 0; i < turns.length; i++) {
    const t = turns[i];
    if (t.role !== "user" || !t.instruction) continue;
    // Look at the replies that followed, before the owner spoke again.
    const shas = new Set();
    for (let j = i + 1, seen = 0; j < turns.length && seen < lookahead; j++) {
      if (turns[j].role === "user") break;
      seen++;
      for (const m of turns[j].text.matchAll(SHA_RE)) shas.add(m[1]);
    }
    found.push({
      when: t.ts,
      text: t.text.length > 300 ? t.text.slice(0, 300) + " …" : t.text,
      claimedShas: [...shas],
    });
  }
  return found;
}

/** Which of the claimed shas actually resolve to commits? */
export function resolveShas(shas, repo = ".") {
  const real = [], phantom = [];
  for (const sha of shas) {
    try {
      execFileSync("git", ["-C", repo, "cat-file", "-e", `${sha}^{commit}`], { stdio: "ignore" });
      real.push(sha);
    } catch { phantom.push(sha); }
  }
  return { real, phantom };
}

export function transcripts(dir) {
  const out = [];
  const walk = (d) => {
    let e; try { e = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const x of e) {
      const p = path.join(d, x.name);
      // Subagent transcripts carry MY prompts, not the owner's. Including them would count my own
      // instructions to myself as promises the owner made me — a ledger that flatters the author.
      if (x.isDirectory()) { if (x.name !== "subagents") walk(p); }
      else if (x.name.endsWith(".jsonl")) out.push(p);
    }
  };
  walk(dir);
  return out.sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs);
}

/* ------------------------------------------------------------------ selftest */

function selfTest() {
  let pass = 0, fail = 0;
  const check = (ok, what) => { ok ? pass++ : (fail++, console.log(`  FAIL  ${what}`)); };

  // real owner turns that ARE instructions
  for (const t of [
    "for everything u have detected and not protected implement protection now",
    "implement graphify in the way that is as effective but as u see fit",
    "next time js put the url in ideas with a description of the reel",
    "if not using the tool gotta make our own like the screen watch thing",
    "add this to ideas",
    "Build all of them",
    "i want like an overlay that always watches",
  ]) check(isInstruction(t), `should be an INSTRUCTION: ${t.slice(0, 55)}`);

  // real owner turns that are NOT instructions
  for (const t of [
    "next reel",
    "explain 3",
    "cl its trash",
    "https://www.instagram.com/reel/DcbznNmS3ZX/",
    "how did u implement reel 8",
    "ok",
    "1 no more omni route explain 2?",
    "how are u planning to learn from ur past mistakes",
    "what did you change in the gate",
    "isnt the graphify code public",
  ]) check(!isInstruction(t), `should NOT be an instruction: ${t.slice(0, 55)}`);

  check(!isInstruction(""), "empty is not an instruction");
  check(!isInstruction("This session is being continued from a previous conversation. build everything"),
    "a compaction summary is not an instruction however many verbs it contains");

  // evidence scoring, both directions
  const commits = [
    { sha: "aaa", iso: "2026-08-28T10:00:00Z", subject: "ideas: capture the url and description", body: "", files: "ideas/INBOX.md" },
    { sha: "bbb", iso: "2026-08-20T10:00:00Z", subject: "unrelated refactor", body: "", files: "src/x.ts" },
  ];
  const kept = verdictFor("put the url in ideas with a description", commits, { after: "2026-08-27" });
  check(kept.verdict === "kept", `a matching later commit reads as KEPT (got ${kept.verdict} @ ${kept.score.toFixed(2)})`);
  const none = verdictFor("build the quantum flux capacitor subsystem", commits, { after: "2026-08-27" });
  check(none.verdict === "no-trace", "an instruction with no matching commit reads as NO TRACE");

  // the ordering rule — work that predates the instruction cannot be evidence for it
  const before = verdictFor("put the url in ideas with a description", commits, { after: "2026-08-29" });
  check(before.verdict === "no-trace", "a commit BEFORE the instruction is not evidence for it");

  check(verdictFor("do it", commits, {}).verdict === "unscorable",
    "an instruction with no distinctive words is UNSCORABLE, not silently marked kept");
  check(scoreMatch(["alpha", "beta"], "alpha only") === 0.5, "partial matches score partially");

  // Check the checker. The first draft parsed git log wrongly and saw ONE commit, which turned every
  // instruction into NO TRACE — a tool confidently wrong about the thing it exists to measure. An
  // audit that can only see one commit must never be allowed to report a verdict.
  const real = loadCommits(".", 50);
  // The guard above is about a PARSER that sees one commit, not a repo that has one. Those are
  // different failures and only one of them is a bug: a fresh or shallow clone genuinely has a
  // short history, and failing there reports the clone rather than the code. So compare what the
  // parser saw against what git says is actually there. A parser that drops commits still FAILS
  // hard; a genuinely short history is reported as NOT CHECKED, never as a pass.
  const actual = Number(execFileSync("git", ["rev-list", "--count", "HEAD"], { encoding: "utf8" }).trim());
  const visible = Math.min(actual, 50);
  if (visible > 5) {
    check(real.length > 5, `git history actually parses (${real.length} commits seen, expected > 5)`);
  } else {
    check(real.length === visible,
      `git history parses as far as it goes (${real.length} of ${visible} commit(s))`);
    console.log(`  NOT CHECKED  parsing at depth — this repo has only ${actual} commit(s); ` +
      `clone with full history to exercise it`);
  }
  check(real.every((c) => /^[0-9a-f]{40}$/.test(c.sha)), "every parsed commit has a real sha");
  check(real.every((c) => /^\d{4}-\d{2}-\d{2}/.test(c.iso)), "every parsed commit has a real date");

  // sha evidence, both directions
  const rs = resolveShas([real[0].sha.slice(0, 7), "deadbee"]);
  check(rs.real.length === 1 && rs.phantom.length === 1,
    "a real sha resolves and an invented one is reported as phantom, not ignored");
  check(!isInstruction("Your task is to create a power box number by reordering the digits"),
    "a pasted exercise is not a standing instruction");

  console.log(`\n${fail === 0 ? "PASS" : "FAIL"} — kept-promises: ${pass} passed, ${fail} failed`);
  return fail;
}

/* ------------------------------------------------------------------ cli */

if (import.meta.url === `file://${process.argv[1]}`) {
  const argv = process.argv.slice(2);
  if (argv.includes("--selftest")) process.exit(selfTest() ? 1 : 0);

  const base = path.join(process.env.HOME || "/root", ".claude", "projects",
    "-" + process.cwd().replace(/^\//, "").replace(/\//g, "-"));
  const files = argv.includes("--all") ? transcripts(base) : transcripts(base).slice(0, 1);
  if (!files.length) { console.error("no transcripts found"); process.exit(2); }

  const commits = loadCommits(".", 500);
  const rows = [];
  for (const f of files) for (const i of scanTranscript(f)) {
    const v = verdictFor(i.text, commits, { after: i.when });
    const { real, phantom } = resolveShas(i.claimedShas || []);
    // A real commit quoted in the reply beats any keyword score. A quoted sha that does not exist is
    // the loudest possible finding and is never quietly upgraded.
    if (phantom.length) rows.push({ ...i, ...v, verdict: "phantom-sha", phantom });
    else if (real.length) rows.push({ ...i, ...v, verdict: "kept", score: 1, commit: commits.find((c) => real.some((r) => c.sha.startsWith(r))) || v.commit, linked: real });
    else rows.push({ ...i, ...v });
  }

  const by = (v) => rows.filter((r) => r.verdict === v);
  const openOnly = argv.includes("--open");

  console.log(`# kept-promises — ${rows.length} instruction(s) across ${files.length} transcript(s), ${commits.length} commits searched\n`);
  console.log(`  KEPT      ${by("kept").length}\t a later commit matches strongly`);
  console.log(`  WEAK      ${by("weak").length}\t something matches thinly — needs eyes`);
  console.log(`  NO TRACE  ${by("no-trace").length}\t nothing in history matches`);
  console.log(`  unscorable ${by("unscorable").length}\t too few distinctive words to search on`);
  const ph = by("phantom-sha");
  console.log(`  PHANTOM   ${ph.length}\t a commit sha was QUOTED IN THE REPLY that does not exist${ph.length ? " ← the exact failure being asked about" : ""}\n`);

  const show = openOnly ? [...ph, ...by("no-trace"), ...by("weak")] : rows;
  for (const r of show) {
    const tag = r.verdict.toUpperCase().padEnd(10);
    console.log(`${tag} ${(r.when || "").slice(0, 10)}  ${r.text.replace(/\n+/g, " ").slice(0, 150)}`);
    if (r.phantom) console.log(`           ↳ QUOTED BUT NONEXISTENT: ${r.phantom.join(", ")}`);
    else if (r.linked) console.log(`           ↳ linked by sha ${r.linked.join(", ")} — ${r.commit ? r.commit.subject.slice(0, 80) : ""}`);
    else if (r.commit && r.verdict !== "no-trace") console.log(`           ↳ ${r.commit.sha.slice(0, 7)} ${r.commit.subject.slice(0, 90)} (keyword match, ${(r.score * 100) | 0}%)`);
    console.log("");
  }
  console.log(`NO TRACE is a REVIEW LIST, not an accusation: an instruction answered in chat needs no`);
  console.log(`commit, and a commit that used different words will be missed. WEAK is where the real`);
  console.log(`risk lives — something landed, but maybe not the thing that was asked for.`);
}
